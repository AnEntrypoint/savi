import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SPEC_URL = 'https://www.spawn.co/openapi.json'
const here = path.dirname(fileURLToPath(import.meta.url))
const specFile = path.join(here, 'openapi.json')
const skipDirs = new Set(['.git', '.playwriter', 'runs', 'site', 'node_modules', 'sources', 'scripts'])
const skipPrefixes = ['.spawn/reference/http/raw/']
const skipFiles = new Set(['ENDPOINTS.md'])
const groups = [
  { key: 'listed', title: 'Listed in the published spec' },
  { key: 'per-game', title: 'Listed with a per-game or per-world id (404 can mean no such game, world or room)' },
  { key: 'partial', title: 'Listed but disabled or partial (its children are listed)' },
  { key: 'absent', title: 'Not in the published spec' }
]

export function loadSpecPaths() {
  const spec = JSON.parse(readFileSync(specFile, 'utf8'))
  return new Set(Object.keys(spec.paths || {}))
}

const uuid = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/g

export function normalize(raw) {
  const cleaned = raw.replace(/[.,;:)\]'"`/]+$/, '').replace(uuid, '{id}')
  const opens = (cleaned.match(/\{/g) || []).length
  const closes = (cleaned.match(/\}/g) || []).length
  if (opens !== closes || /[<>]/.test(cleaned) || cleaned.length < 6) return null
  return cleaned
}

function patternRegex(pattern, tail = '') {
  const body = pattern.split(/(\{[^}]+\})/).map((part) => /^\{[^}]+\}$/.test(part) ? '[^/]+' : part.replace(/[.*+?^$()|[\]\\]/g, '\\$&')).join('')
  return new RegExp('^' + body + tail + '$')
}

function walk(dir, root, out) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    const rel = path.relative(root, full).split(path.sep).join('/')
    if (entry.isDirectory()) {
      if (!skipDirs.has(entry.name)) walk(full, root, out)
    } else if (entry.isFile()) {
      if (skipFiles.has(rel) || skipPrefixes.some((prefix) => rel.startsWith(prefix))) continue
      out.push(rel)
    }
  }
  return out
}

export function namedEndpoints(root) {
  const found = new Set()
  for (const rel of walk(root, root, [])) {
    const data = readFileSync(path.join(root, rel))
    if (data.includes(0)) continue
    for (const match of data.toString('utf8').matchAll(/\/api\/[A-Za-z0-9_\-/.{}<>:]*/g)) {
      const endpoint = normalize(match[0])
      if (endpoint) found.add(endpoint)
    }
  }
  return [...found].sort()
}

export function classify(endpoint, specPaths) {
  const listed = [...specPaths].some((known) => patternRegex(known).test(endpoint))
  if (listed) return endpoint.includes('{') ? 'per-game' : 'listed'
  const hasChildren = [...specPaths].some((known) => patternRegex(endpoint, '/.*').test(known))
  return hasChildren ? 'partial' : 'absent'
}

export function buildEndpointsPage(root) {
  const specPaths = loadSpecPaths()
  const named = namedEndpoints(root)
  const buckets = new Map(groups.map((group) => [group.key, []]))
  for (const endpoint of named) buckets.get(classify(endpoint, specPaths)).push(endpoint)
  const lines = [
    '# Endpoint status',
    '',
    'Generated by scripts/endpoints.mjs from scripts/openapi.json (' + specPaths.size + ' paths) and the endpoints the manual names (' + named.length + '). Regenerate with `node scripts/endpoints.mjs .`; do not edit by hand.',
    ''
  ]
  for (const group of groups) {
    lines.push('## ' + group.title + ' (' + buckets.get(group.key).length + ')', '')
    for (const endpoint of buckets.get(group.key)) lines.push('- ' + endpoint)
    lines.push('')
  }
  return lines.join('\n')
}

export async function syncSpec() {
  const response = await fetch(SPEC_URL)
  if (!response.ok) throw new Error('spec fetch failed: ' + response.status)
  const body = await response.text()
  JSON.parse(body)
  writeFileSync(specFile, body, 'utf8')
  return body.length
}

const invoked = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invoked) {
  if (process.argv[2] === '--sync') {
    console.log(JSON.stringify({ synced: await syncSpec() }))
  } else {
    const root = path.resolve(process.argv[2] || '.')
    writeFileSync(path.join(root, 'ENDPOINTS.md'), buildEndpointsPage(root), 'utf8')
    console.log(JSON.stringify({ named: namedEndpoints(root).length, written: 'ENDPOINTS.md' }))
  }
}
